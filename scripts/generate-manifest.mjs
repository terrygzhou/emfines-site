#!/usr/bin/env node
// EMF-6 / add-asset-gallery — build-time asset manifest generator.
//
// Reads public/assets/_manifest.csv, cross-checks against the image files on
// disk, and emits src/generated/assets-manifest.ts (gitignored). Drift
// (missing-file rows, orphan files) is reported to the console — the build
// never fails on it, and missing files are excluded so no <img> can 404.
//
// Pure logic (CSV parse + cross-check) lives in src/lib/gallery.ts and is
// consumed here through the esbuild bundle that prebuild/predev/pretest create
// first. Node builtins only — no dependencies (constitution I).

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { extname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  UI_ASSETS,
  buildManifest,
  categoryCounts,
  parseManifestCsv,
} from '../node_modules/.cache/gallery.mjs';

const root = join(fileURLToPath(new URL('..', import.meta.url)));
const assetsDir = join(root, 'public', 'assets');
const outPath = join(root, 'src', 'generated', 'assets-manifest.ts');

const IMAGE_EXT = new Set(['.jpg', '.jpeg', '.png', '.webp']);
const MANIFEST = '_manifest.csv';

if (!existsSync(assetsDir)) {
  console.warn(`[assets-manifest] ${assetsDir} not found — emitting empty manifest.`);
  writeEmpty(outPath, assetsDir);
  process.exit(0);
}

const csvPath = join(assetsDir, MANIFEST);
if (!existsSync(csvPath)) {
  console.warn(`[assets-manifest] ${MANIFEST} not found — all images will render with fallback metadata.`);
}

const rows = existsSync(csvPath) ? parseManifestCsv(readFileSync(csvPath, 'utf8')) : [];
const diskFiles = readdirSync(assetsDir).filter((f) => {
  const e = extname(f).toLowerCase();
  return IMAGE_EXT.has(e) && f !== MANIFEST;
});

// UI_ASSETS (e.g. the header logo) live in public/assets but are not gallery
// content: buildManifest excludes them from items + drift.orphans and reports
// which are present on disk as uiAssets (add-header-logo).
const { items, drift, uiAssets } = buildManifest(rows, diskFiles, UI_ASSETS);

// AC-6 drift report.
if (drift.missingFiles.length > 0) {
  for (const f of drift.missingFiles) console.warn(`[assets-manifest] DRIFT: manifest row missing file: ${f}`);
}
if (drift.orphans.length > 0) {
  for (const f of drift.orphans) console.warn(`[assets-manifest] DRIFT: image on disk without manifest row: ${f}`);
}
console.log(
  `[assets-manifest] ${items.length} image(s) across ${categoryCounts(items).length} categor(ies); ` +
    `${drift.missingFiles.length} missing-file row(s), ${drift.orphans.length} orphan(s).`,
);

mkdirSync(join(root, 'src', 'generated'), { recursive: true });
writeFileSync(outPath, emitModule(items, categoryCounts(items), undefined, uiAssets));
console.log(`[assets-manifest] wrote ${outPath.replace(join(root, ''), '')}`);

function writeEmpty(out, why) {
  mkdirSync(join(root, 'src', 'generated'), { recursive: true });
  writeFileSync(out, emitModule([], [], why));
}

function emitModule(items, categories, note, uiAssets = []) {
  const banner =
    '// GENERATED by scripts/generate-manifest.mjs — do not edit by hand.\n' +
    (note ? `// ${note}\n` : '') +
    '// Regenerated automatically on `npm run build` / `npm run dev` (prebuild/predev).\n\n';
  return (
    banner +
    `export interface AssetItem {\n` +
    `  name: string;\n` +
    `  src: string;\n` +
    `  category: string;\n` +
    `  design?: string;\n` +
    `  description: string;\n` +
    `  width?: number;\n` +
    `  height?: number;\n` +
    `  bytes?: number;\n` +
    `  fromManifest: boolean;\n}\n\n` +
    `export const assets: AssetItem[] = ${JSON.stringify(items, null, 2)};\n\n` +
    `export const categories: { name: string; count: number }[] = ${JSON.stringify(categories, null, 2)};\n\n` +
    `export const uiAssets: string[] = ${JSON.stringify(uiAssets, null, 2)};\n`
  );
}
